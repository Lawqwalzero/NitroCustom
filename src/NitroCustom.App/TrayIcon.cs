using System.Runtime.InteropServices;
using NitroCustom.Core.Hardware;
using Drawing = System.Drawing;
using Forms = System.Windows.Forms;

namespace NitroCustom.App;

/// <summary>Notification-area icon with a dark context menu: open, profiles.</summary>
public sealed class TrayIcon : IDisposable
{
    private readonly Forms.NotifyIcon _icon;
    private readonly Forms.ContextMenuStrip _menu;
    private readonly Forms.ToolStripSeparator _profilesEnd = new();
    private readonly List<Forms.ToolStripMenuItem> _profileItems = [];

    public event Action? OpenRequested;
    public event Action<ThermalProfile>? ProfileRequested;
    public event Action? ExitRequested;

    public TrayIcon()
    {
        _menu = new Forms.ContextMenuStrip
        {
            Renderer = new Forms.ToolStripProfessionalRenderer(new DarkColors()),
            ShowImageMargin = false,
            ShowCheckMargin = true,
            ForeColor = Drawing.Color.FromArgb(0xE8, 0xE6, 0xE3),
            Font = new Drawing.Font("Segoe UI", 9.5f),
        };
        var open = new Forms.ToolStripMenuItem(Core.Loc.T("Открыть NitroCustom", "Open NitroCustom")) { Font = new Drawing.Font("Segoe UI", 9.5f, Drawing.FontStyle.Bold) };
        open.Click += (_, _) => OpenRequested?.Invoke();
        // "Exit" closes only the app: NitroCustom.Agent keeps the Nitro key (reopens the app) and the mode button working.
        var exit = new Forms.ToolStripMenuItem(Core.Loc.T("Выход", "Exit"));
        exit.Click += (_, _) => ExitRequested?.Invoke();
        _menu.Items.AddRange([open, new Forms.ToolStripSeparator(), _profilesEnd, exit]);
        _profilesEnd.Visible = false;

        _icon = new Forms.NotifyIcon
        {
            Icon = AppIcon.Create(Forms.SystemInformation.SmallIconSize.Width),
            Text = "NitroCustom",
            ContextMenuStrip = _menu,
            Visible = true,
        };
        _icon.MouseClick += (_, e) => { if (e.Button == Forms.MouseButtons.Left) OpenRequested?.Invoke(); };
    }

    /// <summary>Rebuilds the profile items (between the two separators).</summary>
    public void SetProfiles(IEnumerable<ThermalProfile> supported)
    {
        foreach (var item in _profileItems) _menu.Items.Remove(item);
        _profileItems.Clear();
        var index = _menu.Items.IndexOf(_profilesEnd);
        foreach (var p in Texts.ProfileOrder.Where(supported.Contains))
        {
            var item = new Forms.ToolStripMenuItem(Texts.Long(p)) { Tag = p };
            item.Click += (_, _) => ProfileRequested?.Invoke(p);
            _menu.Items.Insert(index++, item);
            _profileItems.Add(item);
        }
        _profilesEnd.Visible = _profileItems.Count > 0;
    }

    public void SetCurrentProfile(ThermalProfile? profile)
    {
        foreach (var item in _profileItems) item.Checked = (ThermalProfile)item.Tag! == profile;
    }

    public void SetEnabled(bool connected)
    {
        foreach (var item in _profileItems) item.Enabled = connected;
    }

    /// <summary>Tooltip, max 127 characters.</summary>
    public void SetTooltip(string text) => _icon.Text = text.Length > 127 ? text[..127] : text;

    public void Dispose()
    {
        _icon.Visible = false;
        _icon.Dispose();
        _menu.Dispose();
    }

    private sealed class DarkColors : Forms.ProfessionalColorTable
    {
        private static readonly Drawing.Color Bg = Drawing.Color.FromArgb(0x1A, 0x1C, 0x20);
        private static readonly Drawing.Color Hi = Drawing.Color.FromArgb(0x2A, 0x2D, 0x33);
        private static readonly Drawing.Color Line = Drawing.Color.FromArgb(0x2A, 0x2D, 0x33);
        private static readonly Drawing.Color Accent = Drawing.Color.FromArgb(0xE3, 0x26, 0x2B);

        public override Drawing.Color ToolStripDropDownBackground => Bg;
        public override Drawing.Color ImageMarginGradientBegin => Bg;
        public override Drawing.Color ImageMarginGradientMiddle => Bg;
        public override Drawing.Color ImageMarginGradientEnd => Bg;
        public override Drawing.Color MenuBorder => Line;
        public override Drawing.Color MenuItemBorder => Hi;
        public override Drawing.Color MenuItemSelected => Hi;
        public override Drawing.Color SeparatorDark => Line;
        public override Drawing.Color SeparatorLight => Bg;
        public override Drawing.Color CheckBackground => Accent;
        public override Drawing.Color CheckSelectedBackground => Accent;
        public override Drawing.Color CheckPressedBackground => Accent;
    }
}

/// <summary>App icon from Assets\nitrocustom.ico (generated by tools\make_icon.ps1).</summary>
public static class AppIcon
{
    public static readonly Uri Uri = new("pack://application:,,,/Assets/nitrocustom.ico");

    public static Drawing.Icon Create(int size)
    {
        using var stream = System.Windows.Application.GetResourceStream(Uri)!.Stream;
        return new Drawing.Icon(stream, new Drawing.Size(size, size));
    }
}
